#!/usr/bin/env python3
"""
ETL pipeline for the Fraud Detection Data Warehouse (Phase 2).

    Source CSV files -> project_staging (raw_*, stg_*) -> project_dw (dim_*, fact_*) -> project_reporting (vw_*)

Steps (each step is written to project_dw.etl_audit_log):
    1  create schemas              sql/01_create_schemas.sql
    2  create staging tables       sql/02_staging_ddl.sql
    3  EXTRACT  CSV -> raw_*       PostgreSQL COPY (this script)
    4  TRANSFORM raw_* -> stg_*    sql/03_staging_clean.sql
    5  create warehouse tables     sql/04_dw_ddl.sql
    6  LOAD dimensions             sql/05_load_dimensions.sql
    7  LOAD facts                  sql/06_load_facts.sql
    8  reporting views             sql/07_reporting_views.sql
    9  data quality checks         sql/08_data_quality.sql

Usage:
    python etl/etl_pipeline.py --data-dir data --host localhost --user postgres --password secret
Settings can also come from the environment: PGHOST, PGPORT, PGUSER, PGPASSWORD, PGDATABASE.
Exit code is 0 when all data quality checks pass, 1 otherwise.
"""
import argparse
import os
import sys
import time
from datetime import datetime
from pathlib import Path

import psycopg2
from psycopg2 import sql as psql

ROOT = Path(__file__).resolve().parent.parent
SQL_DIR = ROOT / "sql"

# file name, target raw table, target columns (row_id is generated by the database)
COPY_SPEC = [
    ("accounts.csv", "project_staging.raw_accounts", ["sender_account", "receiver_account", "amount", "is_fraud"]),
    ("transaction_type.csv", "project_staging.raw_transaction_type",
     ["transaction_id", "transaction_type", "location_region", "ip_prefix", "txn_timestamp"]),
    ("behavior_risk.csv", "project_staging.raw_behavior_risk",
     ["login_frequency", "session_duration", "purchase_pattern", "risk_score", "anomaly"]),
    ("user.csv", "project_staging.raw_user",
     ["customer_name", "customer_email", "merchant_name", "merchant_email", "card_number", "card_expiry", "device_type"]),
]


def parse_args():
    p = argparse.ArgumentParser(description="Fraud DW ETL pipeline")
    p.add_argument("--data-dir", default=str(ROOT / "data"), help="folder with the four CSV files")
    p.add_argument("--host", default=os.getenv("PGHOST", "localhost"))
    p.add_argument("--port", default=os.getenv("PGPORT", "5432"))
    p.add_argument("--user", default=os.getenv("PGUSER", "postgres"))
    p.add_argument("--password", default=os.getenv("PGPASSWORD", ""))
    p.add_argument("--dbname", default=os.getenv("PGDATABASE", "fraud_dw"))
    p.add_argument("--batch-id", type=int, default=1, help="ETL batch id stored on every fact row")
    return p.parse_args()


def connect(args, dbname):
    kw = dict(host=args.host, port=args.port, user=args.user, dbname=dbname)
    if args.password:
        kw["password"] = args.password
    return psycopg2.connect(**kw)


def ensure_database(args):
    """Create the database if it does not exist (same effect as sql/00_create_database.sql)."""
    conn = connect(args, "postgres")
    conn.autocommit = True
    with conn.cursor() as cur:
        cur.execute("SELECT 1 FROM pg_database WHERE datname = %s", (args.dbname,))
        if cur.fetchone() is None:
            cur.execute(psql.SQL("CREATE DATABASE {} ENCODING 'UTF8'").format(psql.Identifier(args.dbname)))
            print(f"created database {args.dbname}")
    conn.close()


class Pipeline:
    def __init__(self, args):
        self.args = args
        self.conn = connect(args, args.dbname)
        self.pending_log = []          # audit lines written before project_dw.etl_audit_log exists
        self.dw_ready = False

    # ---------- helpers ----------
    def run_sql_file(self, name):
        text = (SQL_DIR / name).read_text(encoding="utf-8")
        with self.conn.cursor() as cur:
            cur.execute("SELECT set_config('etl.batch_id', %s, false)", (str(self.args.batch_id),))
            cur.execute(text)
        self.conn.commit()

    def count(self, table):
        with self.conn.cursor() as cur:
            cur.execute(f"SELECT COUNT(*) FROM {table}")
            return cur.fetchone()[0]

    def audit(self, step, status, rows, started, message=None):
        rec = (self.args.batch_id, step, status, rows, started, datetime.now(), message)
        if not self.dw_ready:
            self.pending_log.append(rec)
            return
        with self.conn.cursor() as cur:
            cur.execute("INSERT INTO project_dw.etl_audit_log (batch_id, step_name, status, rows_processed, started_at, finished_at, message) "
                        "VALUES (%s,%s,%s,%s,%s,%s,%s)", rec)
        self.conn.commit()

    def flush_pending(self):
        with self.conn.cursor() as cur:
            for rec in self.pending_log:
                cur.execute("INSERT INTO project_dw.etl_audit_log (batch_id, step_name, status, rows_processed, started_at, finished_at, message) "
                            "VALUES (%s,%s,%s,%s,%s,%s,%s)", rec)
        self.conn.commit()
        self.pending_log.clear()

    def step(self, label, fn, count_table=None):
        started = datetime.now()
        t0 = time.time()
        try:
            fn()
            rows = self.count(count_table) if count_table else None
            self.audit(label, "SUCCESS", rows, started)
            print(f"[ok] {label:<42} {'' if rows is None else f'{rows:>10,} rows'}  ({time.time() - t0:.1f}s)")
        except Exception as exc:                       # log and stop: a failed load must not continue silently
            self.conn.rollback()
            self.audit(label, "FAILED", None, started, str(exc)[:500])
            print(f"[FAILED] {label}: {exc}")
            raise

    # ---------- EXTRACT ----------
    def extract(self):
        data_dir = Path(self.args.data_dir)
        with self.conn.cursor() as cur:
            cur.execute("TRUNCATE project_staging.raw_accounts, project_staging.raw_transaction_type, "
                        "project_staging.raw_behavior_risk, project_staging.raw_user RESTART IDENTITY")
            for fname, table, cols in COPY_SPEC:
                path = data_dir / fname
                if not path.exists():
                    raise FileNotFoundError(f"missing source file: {path}")
                copy_sql = f"COPY {table} ({', '.join(cols)}) FROM STDIN WITH (FORMAT csv, HEADER true)"
                with open(path, "r", encoding="utf-8-sig", newline="") as fh:
                    cur.copy_expert(copy_sql, fh)
        self.conn.commit()

    # ---------- run ----------
    def run(self):
        s = self.step
        s("1 create schemas", lambda: self.run_sql_file("01_create_schemas.sql"))
        s("2 create staging tables", lambda: self.run_sql_file("02_staging_ddl.sql"))
        s("3 extract CSV -> raw_accounts", self.extract, "project_staging.raw_accounts")
        s("4 transform raw_* -> stg_*", lambda: self.run_sql_file("03_staging_clean.sql"), "project_staging.stg_accounts")
        s("5 create warehouse tables", lambda: self.run_sql_file("04_dw_ddl.sql"))
        self.dw_ready = True
        self.flush_pending()
        s("6 load dimensions", lambda: self.run_sql_file("05_load_dimensions.sql"), "project_dw.dim_customer")
        s("7 load facts", lambda: self.run_sql_file("06_load_facts.sql"), "project_dw.fact_transactions")
        s("8 reporting views", lambda: self.run_sql_file("07_reporting_views.sql"))
        s("9 data quality checks", lambda: self.run_sql_file("08_data_quality.sql"), "project_dw.dq_results")

    def summary(self):
        with self.conn.cursor() as cur:
            cur.execute("SELECT check_group, COUNT(*) FILTER (WHERE status='PASS'), COUNT(*) FILTER (WHERE status='FAIL') "
                        "FROM project_dw.dq_results GROUP BY check_group ORDER BY 1")
            rows = cur.fetchall()
        print("\nData quality summary")
        failed = 0
        for grp, ok, bad in rows:
            print(f"  {grp:<13} pass {ok:>3}   fail {bad:>3}")
            failed += bad
        return failed


def main():
    args = parse_args()
    ensure_database(args)
    pipe = Pipeline(args)
    try:
        pipe.run()
        failed = pipe.summary()
    finally:
        pipe.conn.close()
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
